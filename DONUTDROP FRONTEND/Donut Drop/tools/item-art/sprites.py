def grid(name):
    palette, art = SPRITES[name]
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
        for ch in r:
            assert ch == '.' or ch in palette, (name, ch)
    return palette, rows
