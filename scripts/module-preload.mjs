#!/usr/bin/env node
/* Writes a <link rel="modulepreload"> for every module the page loads into index.html's head.
 *
 * The page is some fifty ES modules imported three deep: index.html names app.js, app.js imports
 * the rest, and a few of those import more. A browser only learns of a module by parsing the one
 * that imports it, so without help it fetches them in three rounds, one after another -- and the
 * assets are served "max-age=0, must-revalidate" (nginx.conf), so even a returning visitor pays
 * every round as a revalidation. The preloads name the whole graph up front, from the head, and
 * the browser asks for all of it at once.
 *
 * Only the static graph: a module loaded by import() is loaded on demand on purpose (the dev
 * bench, the cutscenes, three.js), and preloading it would fetch what most visits never run.
 *
 *   node scripts/module-preload.mjs           rewrite the generated block in index.html
 *   node scripts/module-preload.mjs --check   exit 1 if it is out of date
 *
 * services/api-gateway/tests/module-preload.test.ts runs the same check.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FRONTEND = path.join(repo, 'DONUTDROP FRONTEND/Donut Drop');
export const INDEX_HTML = path.join(FRONTEND, 'index.html');

const BEGIN = '<!-- ── module preloads: generated by scripts/module-preload.mjs, do not edit by hand ── -->';
const END = '<!-- ── end module preloads ── -->';

/** The page's entry modules, exactly as index.html spells them (query string and all). */
export function entryModules(html) {
  return [...html.matchAll(/<script\s+type="module"\s+src="([^"]+)"/g)].map((match) => match[1]);
}

/**
 * Every relative specifier a module imports or re-exports statically. Statement position only:
 * the specifier list may span lines, but nothing but names, braces and commas sits between the
 * keyword and `from`, so a string that merely mentions an import never matches.
 */
export function staticImports(source) {
  const found = [];
  const pattern = /(?:^|[;}])\s*(?:import|export)\s+(?:[\w$*{},\s]+?\s+from\s+)?['"](\.{1,2}\/[^'"]+)['"]/gm;
  for (const match of source.matchAll(pattern)) found.push(match[1]);
  return found;
}

/** The whole static graph, as page-relative URLs, entry modules first, then in discovery order. */
export function moduleGraph(html, readModule) {
  const entries = entryModules(html);
  const seen = new Set(entries.map((entry) => entry.split('?')[0]));
  const order = [...entries];
  const queue = entries.map((entry) => entry.split('?')[0]);
  while (queue.length) {
    const current = queue.shift();
    const dir = path.posix.dirname(current);
    for (const specifier of staticImports(readModule(current))) {
      const resolved = path.posix.normalize(path.posix.join(dir, specifier));
      if (seen.has(resolved)) continue;
      seen.add(resolved);
      order.push(resolved);
      queue.push(resolved);
    }
  }
  return order;
}

export function renderBlock(modules) {
  return [BEGIN, ...modules.map((href) => `<link rel="modulepreload" href="${href}" />`), END].join('\n');
}

/** index.html as it should read, line endings normalised to \n. */
export function expectedHtml(html, readModule) {
  const text = html.replace(/\r\n/g, '\n');
  const start = text.indexOf(BEGIN);
  const stop = text.indexOf(END, start);
  if (start < 0 || stop < 0) throw new Error('index.html is missing the module preload markers');
  // The graph is read from the page without the block, so the block cannot feed itself.
  const block = renderBlock(moduleGraph(text, readModule));
  return text.slice(0, start) + block + text.slice(stop + END.length);
}

export function readFrontendModule(relative) {
  return readFileSync(path.join(FRONTEND, relative), 'utf8');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const raw = readFileSync(INDEX_HTML, 'utf8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const current = raw.replace(/\r\n/g, '\n');
  const next = expectedHtml(raw, readFrontendModule);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('index.html module preloads are out of date: run node scripts/module-preload.mjs');
      process.exit(1);
    }
    console.log('index.html module preloads are up to date');
  } else {
    writeFileSync(INDEX_HTML, next.replace(/\n/g, eol));
    console.log(next === current ? 'index.html already up to date' : 'index.html updated');
  }
}
